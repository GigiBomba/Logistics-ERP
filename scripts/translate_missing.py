def iter_leaves(obj, path=()):
    if isinstance(obj, dict):
        for k, v in obj.items(): yield from iter_leaves(v, path + (k,))
    elif isinstance(obj, list):
        for i, v in enumerate(obj): yield from iter_leaves(v, path + (i,))
    else: yield path, obj

def set_at(obj, path, value):
    for key in path[:-1]: obj = obj[key]
    obj[path[-1]] = value

def get_at(obj, path):
    for key in path: obj = obj[key]
    return obj

def load_json(path):
    with open(path, "r", encoding="utf-8") as f: return json.load(f)

def save_json(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

def should_translate(val):
    if not isinstance(val, str) or not val: return False
    if val.strip() in PRESERVE: return False
    if re.match(r"^\\{.*\\}$", val.strip()): return False
    return True


