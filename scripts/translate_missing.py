def translate_file(lang_code, trans_dict):
    en_path = os.path.join(TRANS_DIR, "en.json")
    tgt_path = os.path.join(TRANS_DIR, f"{lang_code}.json")
    en = load_json(en_path)
    tgt = load_json(tgt_path)
    count = 0
    for path, en_val in iter_leaves(en):
        if not should_translate(en_val): continue
        try:
            tgt_val = get_at(tgt, path)
        except (KeyError, IndexError, TypeError): continue
        if isinstance(tgt_val, str) and tgt_val == en_val:
            tr = trans_dict.get(en_val)
            if tr:
                set_at(tgt, path, tr)
                count += 1
    save_json(tgt_path, tgt)
    return count

def count_stats(lang_code):
    en_path = os.path.join(TRANS_DIR, "en.json")
    tgt_path = os.path.join(TRANS_DIR, f"{lang_code}.json")
    en = load_json(en_path); tgt = load_json(tgt_path)
    total = 0; untranslated = 0
    for path, en_val in iter_leaves(en):
        if not should_translate(en_val): continue
        total += 1
        try:
            v = get_at(tgt, path)
        except: continue
        if isinstance(v, str) and v == en_val: untranslated += 1
    return total, untranslated

