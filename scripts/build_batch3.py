"""Build the complete translate_batch3.py script with all 4 dictionaries."""
import io, sys, json, os
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
sys.stderr = io.TextIOWrapper(sys.stderr.buffer, encoding='utf-8')

dir = os.path.join(os.path.dirname(__file__), "..", "data", "translations")
en = json.load(open(os.path.join(dir, "en.json"), encoding='utf-8-sig'))

def flatten(d, prefix=''):
    items = {}
    for k, v in d.items():
        key = f'{prefix}.{k}' if prefix else k
        if isinstance(v, dict):
            items.update(flatten(v, key))
        else:
            items[key] = v
    return items
en_flat = flatten(en)

all_untrans_values = set()
for code in ['sr', 'el', 'sk', 'pl']:
    data = json.load(open(os.path.join(dir, f'{code}.json'), encoding='utf-8-sig'))
    flat = flatten(data)
    for k in sorted(en_flat.keys()):
        if k in flat and isinstance(en_flat[k], str) and isinstance(flat[k], str) and flat[k] == en_flat[k] and en_flat[k] != '':
            all_untrans_values.add(en_flat[k])

# Now read _all_untrans.txt to get sorted list
