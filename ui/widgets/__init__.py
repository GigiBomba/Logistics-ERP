def section_header(parent: QWidget, text: str, _return: bool = False):
    """Factory matching the old ``ui.widgets.section_header`` signature."""
    header = SectionHeader(parent, text, _return=_return)
    if _return:
        return header.label_returned
    return header


def kpi_card(parent: QWidget, title: str, value: str) -> KpiCard:
    """Factory matching the old ``ui.widgets.kpi_card`` signature."""
    return KpiCard(parent, title, value)


def themed_combobox(parent: QWidget, **kwargs) -> StyledComboBox:
    """Factory matching the old ``ui.widgets.themed_combobox`` signature."""
    return StyledComboBox(parent, **kwargs)


def field(
    parent: QWidget,
    label_text: str,
    widget: QWidget,
    helper_text: str = "",
) -> QWidget:
    """Form field helper: label + input widget + optional helper text.

    Returns a container widget so callers can add it directly to a layout.
    """
    container = QWidget(parent)
    layout = QVBoxLayout(container)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(S["1"])

    label = QLabel(label_text)
    label.setProperty("fontRole", "label")
    layout.addWidget(label)

    layout.addWidget(widget)

    if helper_text:
        helper = QLabel(helper_text)
        helper.setProperty("fontRole", "helper")
        layout.addWidget(helper)

    return container


