"""Shared PySide6 widget wrappers for the Operion ERP Qt branch.

These classes mirror the API of the CustomTkinter wrappers in ``ui/widgets`` so
that view migration is mostly a matter of changing imports. They intentionally do
**not** embed inline stylesheets; appearance is controlled by the global QSS
sheet generated by ``ui.theme_engine.QtTheme``.
"""

from __future__ import annotations

from typing import Callable, List, Optional

from PySide6.QtCore import Qt, Signal
from PySide6.QtWidgets import (
    QWidget,
    QFrame,
    QLabel,
    QLineEdit,
    QPushButton,
    QCheckBox,
    QRadioButton,
    QComboBox,
    QPlainTextEdit,
    QScrollArea,
    QVBoxLayout,
    QHBoxLayout,
    QSizePolicy,
    QTableWidget,
    QTableWidgetItem,
    QAbstractItemView,
)

from ui.theme import COLORS, S
from ui.styles import Theme


