class StyledCheckBox(QCheckBox):
    """Dark-themed checkbox."""

    toggled_value = Signal(object)

    def __init__(
        self,
        parent: QWidget | None = None,
        text: str = "",
        variable=None,
        onvalue=None,
        offvalue=None,
        **kwargs,
    ):
        super().__init__(text, parent)
        self._onvalue = onvalue
        self._offvalue = offvalue
        if variable is not None:
            # Tk-style variable compatibility: sync the Qt state to the variable.
            self.stateChanged.connect(self._emit_toggled_value)

    def _emit_toggled_value(self, state: int):
        if Qt.CheckState(state) == Qt.Checked:
            self.toggled_value.emit(self._onvalue)
        else:
            self.toggled_value.emit(self._offvalue)


class StyledRadioButton(QRadioButton):
    """Dark-themed radio button."""

    def __init__(self, parent: QWidget | None = None, text: str = "", **kwargs):
        super().__init__(text, parent)


