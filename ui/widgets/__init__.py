class StyledTableWidget(QTableWidget):
    """Dark-themed read-only table with sort support and selection helpers.

    Columns are specified as ``(id, label, width)`` tuples. The last column
    stretches to fill remaining horizontal space.
    """

    rowSelected = Signal(dict)
    rowDoubleClicked = Signal(dict)
    headerClicked = Signal(int, str)

    # ── Density constants ────────────────────────────────────────────────
    DENSITY_COMFORTABLE = 44
    DENSITY_STANDARD = 36
    DENSITY_COMPACT = 28

    def __init__(
        self,
        parent: QWidget | None = None,
        columns: list[tuple] | None = None,
        formatters: dict[str, Callable] | None = None,
        prefs: dict | None = None,
        prefs_key: str | None = None,
    ):
        super().__init__(parent)
        self.setAccessibleName("Data table")
        self.setAccessibleDescription(
            "Use arrow keys to navigate rows. Press Enter to select."
        )
        self._columns: list[tuple] = columns or []
        self._column_ids: list[str] = []
        self._data: list[dict] = []
        self._formatters: dict[str, Callable] = formatters or {}
        self._alignments: dict[str, Qt.AlignmentFlag] = {}
        self._prefs: dict = prefs if prefs is not None else {}
        self._prefs_key: str | None = prefs_key
        self._current_density: int = self.DENSITY_STANDARD

        self.setAlternatingRowColors(True)
        self.setSelectionBehavior(QAbstractItemView.SelectRows)
        self.setSelectionMode(QAbstractItemView.ExtendedSelection)
        self.setEditTriggers(QAbstractItemView.NoEditTriggers)
        self.setShowGrid(False)
        self.verticalHeader().setVisible(False)
        self.verticalHeader().setDefaultSectionSize(self.DENSITY_STANDARD)
        self.horizontalHeader().setFixedHeight(self.DENSITY_STANDARD)
        self.setMinimumHeight(200)
        self.setSortingEnabled(True)
        self.horizontalHeader().setSortIndicatorShown(True)
        # The first column is the implicit default sort.  When sorting is
        # enabled at the end of ``set_data`` without an explicit sort
        # indicator, Qt falls back to column 0 ascending.  Mirror that
        # here so ``_data`` and the visual rows line up from the start.
        if self._columns:
            header = self.horizontalHeader()
            header.setSortIndicator(0, Qt.AscendingOrder)
        # Keep the in-memory data list aligned with the visual row order
        # whenever the user (or code) changes the sort indicator.
        self.horizontalHeader().sortIndicatorChanged.connect(
            self._on_sort_indicator_changed
        )

        self.cellClicked.connect(self._emit_selection)
        self.cellDoubleClicked.connect(self._emit_double_click)
        self.horizontalHeader().sectionClicked.connect(self._on_section_clicked)
        # Persist column widths whenever the user drags a column divider.
        self.horizontalHeader().sectionResized.connect(
            lambda idx, old, new: self.save_column_widths()
        )

        if self._columns:
            self._apply_columns()

    def _apply_columns(self) -> None:
        self.setColumnCount(len(self._columns))
        self._column_ids = []
        labels = []
        for i, (cid, label, width) in enumerate(self._columns):
            self._column_ids.append(cid)
            labels.append(label)
            self.setColumnWidth(i, width)
        self.setHorizontalHeaderLabels(labels)
        if self._columns:
            self.horizontalHeader().setStretchLastSection(True)
            self.horizontalHeader().setSortIndicator(0, Qt.AscendingOrder)

    def _sort_key(self, cid: str):
        """Return a key function that orders ``None`` last and everything
        else by natural comparison.  Used for both ``set_data`` and
        ``_on_sort_indicator_changed``.
        """
        def key(row: dict):
            value = row.get(cid)
            if value is None:
                # Tuple ordering: ``(True, ...)`` sorts after ``(False, ...)``
                # in ascending order, so ``None`` always sinks to the
                # bottom regardless of direction.
                return (True, "")
            return (False, value)
        return key

    def _sort_rows(self, rows: list[dict]) -> list[dict]:
        """Return a copy of *rows* sorted by the table's current sort
        indicator.  Returns the input list unchanged if the indicator
        points past the last column.  This is independent of whether
        ``setSortingEnabled`` is currently true — the indicator is
        always consulted so callers can call us from ``set_data``
        before sorting is enabled.
        """
        if not rows:
            return rows
        header = self.horizontalHeader()
        section = header.sortIndicatorSection()
        order = header.sortIndicatorOrder()
        if section < 0 or section >= len(self._column_ids):
            return list(rows)
        cid = self._column_ids[section]
        reverse = order == Qt.DescendingOrder
        return sorted(rows, key=self._sort_key(cid), reverse=reverse)

    def _on_sort_indicator_changed(
        self, logical_index: int, order: Qt.SortOrder
    ) -> None:
        """Reorder ``self._data`` to match the new visual order whenever
        the sort indicator changes (programmatic or user-driven).  Then
        notify listeners of the *currently selected* row (if any) so
        views that cache a selection by row-index can re-validate.
        """
        if not self._data:
            return
        # Capture the data the user has actually selected *before* we
        # re-sort.  The user expects their selection to follow the
        # data item, not the visual row index.
        previous = self.current_row_data()
        self._data = self._sort_rows(self._data)
        # Qt's QTableWidget will re-position the selection to the same
        # data item on its own.  Re-emit ``rowSelected`` so views that
        # cached by data dict (e.g. ``_selected_id``) can re-fetch.
        if previous is not None:
            self.rowSelected.emit(previous)

    def _on_section_clicked(self, logical_index: int) -> None:
        """User clicked a header — Qt will flip the sort indicator.  We
        don't reorder ``_data`` here (the connected
        ``sortIndicatorChanged`` will fire and handle it), but we
        preserve selection across the visual re-sort so the user keeps
        the same logical row highlighted.
        """
        # No-op: ``sortIndicatorChanged`` does the re-order.
        return

    def column_id_at(self, index: int) -> str:
        """Return the column identifier at *index*, or an empty string."""
        if 0 <= index < len(self._column_ids):
            return self._column_ids[index]
        return ""

    def set_data(self, rows: list[dict]) -> None:
        # ``setSortingEnabled(False)`` would also clear the sort
        # indicator, so we keep the current indicator and just suppress
        # intermediate sorts while populating.
        self.setSortingEnabled(False)
        self.setRowCount(0)
        self._data = self._sort_rows(rows)
        self.setRowCount(len(self._data))
        for r, row in enumerate(self._data):
            for c, cid in enumerate(self._column_ids):
                value = row.get(cid, "")
                fmt = self._formatters.get(cid)
                if fmt is not None and value != "":
                    display = fmt(value)
                else:
                    display = str(value) if value is not None else ""
                item = QTableWidgetItem(display)
                item.setData(Qt.UserRole, value)
                align = self._alignments.get(cid)
                if align is not None:
                    item.setTextAlignment(align)
                self.setItem(r, c, item)
        self.setSortingEnabled(True)

    def set_column_alignment(self, cid: str, alignment: Qt.AlignmentFlag) -> None:
        """Set text alignment for a specific column id."""
        self._alignments[cid] = alignment
        # Re-apply to existing items if data is already loaded
        if not self._data:
            return
        for r, _row in enumerate(self._data):
            if cid in self._column_ids:
                c = self._column_ids.index(cid)
                item = self.item(r, c)
                if item is not None:
                    item.setTextAlignment(alignment)

    def current_row_data(self) -> dict | None:
        row = self.currentRow()
        if 0 <= row < len(self._data):
            return self._data[row]
        return None

    def selected_row_data(self) -> dict | None:
        rows = set()
        for idx in self.selectedIndexes():
            rows.add(idx.row())
        for r in sorted(rows):
            if 0 <= r < len(self._data):
                return self._data[r]
        return None

    def _emit_selection(self, row: int, col: int) -> None:
        if 0 <= row < len(self._data):
            self.rowSelected.emit(self._data[row])

    def _emit_double_click(self, row: int, col: int) -> None:
        if 0 <= row < len(self._data):
            self.rowDoubleClicked.emit(self._data[row])

    # ── Preference helpers ──────────────────────────────────────────────

    def _prefs_set(self, key: str, value: object) -> None:
        """Store *value* under *key* in the preferences store.

        Handles both ``PreferencesManager`` (via ``save_setting``) and
        plain ``dict`` backends.  Non-dict values are JSON-serialised.
        """
        try:
            if hasattr(self._prefs, "save_setting"):
                self._prefs.save_setting(key, json.dumps(value))
            else:
                self._prefs[key] = value
        except Exception:
            pass

    def _prefs_get(self, key: str, default: object = None) -> object:
        """Retrieve a value from the preferences store.

        Returns *default* when the key is missing or on error.
        """
        try:
            if hasattr(self._prefs, "get_setting"):
                raw = self._prefs.get_setting(key)
                if raw is not None:
                    return json.loads(raw)
                return default
            return self._prefs.get(key, default)
        except Exception:
            return default

    # ── Column width persistence ────────────────────────────────────────

    def save_column_widths(self, key: str | None = None) -> None:
        """Save current column widths to preferences."""
        key = key or self._prefs_key
        if not key:
            return
        widths: dict[str, int] = {}
        for col in range(self.columnCount()):
            widths[str(col)] = self.columnWidth(col)
        self._prefs_set(f"table_{key}_col_widths", widths)

    def restore_column_widths(self, key: str | None = None) -> None:
        """Restore saved column widths from preferences."""
        key = key or self._prefs_key
        if not key:
            return
        widths = self._prefs_get(f"table_{key}_col_widths", {})
        if widths and isinstance(widths, dict):
            for col_str, width in widths.items():
                col = int(col_str)
                if 0 <= col < self.columnCount():
                    self.setColumnWidth(col, width)

    # ── Density ─────────────────────────────────────────────────────────

    def set_density(self, density: int) -> None:
        """Set row height: 44=comfortable, 36=standard, 28=compact."""
        density = max(20, min(60, density))
        self.verticalHeader().setDefaultSectionSize(density)
        self._current_density = density
        self.updateGeometry()

    def current_density(self) -> int:
        return self._current_density

    # ── Density menu helper ─────────────────────────────────────────────

    def _build_density_menu(self, parent: QWidget) -> QMenu:
        """Return a ``QMenu`` with three density options.

        Selecting an option persists the choice to preferences and
        applies it to the table.
        """
        from PySide6.QtGui import QAction

        menu = QMenu(parent)

        for label, value in [
            (self.tr("Comfortable"), self.DENSITY_COMFORTABLE),
            (self.tr("Standard"), self.DENSITY_STANDARD),
            (self.tr("Compact"), self.DENSITY_COMPACT),
        ]:
            action = QAction(label, parent)
            action.setCheckable(True)
            action.setChecked(self._current_density == value)
            action.triggered.connect(lambda checked, v=value: self._apply_density(v))
            menu.addAction(action)

        return menu

    def _apply_density(self, density: int) -> None:
        self.set_density(density)
        self._prefs_set(f"table_{self._prefs_key or 'default'}_density", density)


def styled_table(parent: QWidget, columns: list[tuple]) -> StyledTableWidget:
    """Factory matching ``StyledTableWidget(parent, columns)``."""
    return StyledTableWidget(parent, columns)
