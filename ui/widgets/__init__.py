class ScrollableFormContainer(QScrollArea):
    """Scrollable area with a constrained maximum form width.

    Add widgets/layouts to ``.content`` via ``add_widget()`` / ``add_layout()``.
    """

    def __init__(self, parent: QWidget | None = None, max_width: int = 740):
        super().__init__(parent)
        self.setWidgetResizable(True)
        self.setFrameShape(QFrame.NoFrame)

        self.content = QWidget()
        self.content.setMaximumWidth(max_width)
        self.content.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Expanding)

        self.layout = QVBoxLayout(self.content)
        self.layout.setContentsMargins(SP["10"], SP["6"], SP["10"], SP["10"])
        self.layout.setSpacing(SP["6"])
        self.layout.setAlignment(Qt.AlignTop)

        self.setWidget(self.content)

    def add_widget(self, widget: QWidget, stretch: int = 0) -> None:
        self.layout.addWidget(widget, stretch)

    def add_layout(self, layout, stretch: int = 0) -> None:
        self.layout.addLayout(layout, stretch)

    def add_stretch(self, stretch: int = 1) -> None:
        self.layout.addStretch(stretch)


class TwoColRow(QWidget):
    """Horizontal row split into two equal-width columns."""

    def __init__(self, parent: QWidget | None = None):
        super().__init__(parent)
        layout = QHBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.setSpacing(SP["3"])

        self.left = QWidget()
        self.left.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Preferred)
        self.right = QWidget()
        self.right.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Preferred)

        layout.addWidget(self.left, 1)
        layout.addWidget(self.right, 1)

    def left_layout(self) -> QVBoxLayout:
        if self.left.layout() is None:
            self.left.setLayout(QVBoxLayout())
            self.left.layout().setContentsMargins(0, 0, 0, 0)
            self.left.layout().setSpacing(0)
        return self.left.layout()

    def right_layout(self) -> QVBoxLayout:
        if self.right.layout() is None:
            self.right.setLayout(QVBoxLayout())
            self.right.layout().setContentsMargins(0, 0, 0, 0)
            self.right.layout().setSpacing(0)
        return self.right.layout()


