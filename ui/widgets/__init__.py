class StyledLineEdit(QLineEdit):
    """Dark-themed single-line text input.

    Appearance is handled by the global QSS (``QLineEdit`` selector). This
    wrapper only adds convenient defaults and tk-style placeholder support.
    """

    def __init__(
        self,
        parent: Optional[QWidget] = None,
        placeholder: Optional[str] = None,
        height: int = 38,
        text: str = "",
        **kwargs,
    ):
        super().__init__(parent)
        if placeholder:
            self.setPlaceholderText(placeholder)
        if text:
            self.setText(text)
        self.setFixedHeight(height)
        self.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)


class StyledTextEdit(QPlainTextEdit):
    """Dark-themed multi-line text input."""

    def __init__(
        self,
        parent: Optional[QWidget] = None,
        height: Optional[int] = None,
        placeholder: Optional[str] = None,
        text: str = "",
        **kwargs,
    ):
        super().__init__(parent)
        if placeholder:
            self.setPlaceholderText(placeholder)
        if text:
            self.setPlainText(text)
        if height:
            self.setFixedHeight(height)
        self.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Expanding)


class StyledComboBox(QComboBox):
    """Dark-themed dropdown."""

    def __init__(
        self,
        parent: Optional[QWidget] = None,
        values: Optional[List[str]] = None,
        state: str = "normal",
        variable=None,
        **kwargs,
    ):
        super().__init__(parent)
        if values:
            self.addItems(values)
        if state == "readonly":
            self.setEditable(False)
        self.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)
        # ``variable`` is accepted for API compatibility but not used here.
        # Views should connect to currentTextChanged/currentIndexChanged.


