class StyledTableWidget(QTableWidget):
    """Dark-themed read-only table with sort support and selection helpers.

    Columns are specified as ``(id, label, width)`` tuples. The last column
    stretches to fill remaining horizontal space.
    """

    rowSelected = Signal(dict)
    rowDoubleClicked = Signal(dict)
    headerClicked = Signal(int, str)

    def __init__(
        self,
        parent: Optional[QWidget] = None,
        columns: Optional[List[tuple]] = None,
    ):
        super().__init__(parent)
        self._columns: List[tuple] = columns or []
        self._column_ids: List[str] = []
        self._data: List[dict] = []

        self.setAlternatingRowColors(True)
        self.setSelectionBehavior(QAbstractItemView.SelectRows)
        self.setSelectionMode(QAbstractItemView.SingleSelection)
        self.setEditTriggers(QAbstractItemView.NoEditTriggers)
        self.setShowGrid(False)
        self.verticalHeader().setVisible(False)
        self.setSortingEnabled(False)

        self.cellClicked.connect(self._emit_selection)
        self.cellDoubleClicked.connect(self._emit_double_click)

        if self._columns:
            self._apply_columns()

    def _apply_columns(self) -> None:
        self.setColumnCount(len(self._columns))
        self._column_ids = []
        labels = []
        for i, (cid, label, width) in enumerate(self._columns):
            self._column_ids.append(cid)
            labels.append(label)
            self.setColumnWidth(i, width)
        self.setHorizontalHeaderLabels(labels)
        if self._columns:
            self.horizontalHeader().setStretchLastSection(True)

    def set_data(self, rows: List[dict]) -> None:
        self._data = rows
        self.setSortingEnabled(False)
        self.setRowCount(0)
        self.setRowCount(len(rows))
        for r, row in enumerate(rows):
            for c, cid in enumerate(self._column_ids):
                value = row.get(cid, "")
                item = QTableWidgetItem(str(value) if value is not None else "")
                self.setItem(r, c, item)
        self.setSortingEnabled(True)

    def current_row_data(self) -> Optional[dict]:
        row = self.currentRow()
        if 0 <= row < len(self._data):
            return self._data[row]
        return None

    def selected_row_data(self) -> Optional[dict]:
        rows = set()
        for idx in self.selectedIndexes():
            rows.add(idx.row())
        for r in sorted(rows):
            if 0 <= r < len(self._data):
                return self._data[r]
        return None

    def _emit_selection(self, row: int, col: int) -> None:
        if 0 <= row < len(self._data):
            self.rowSelected.emit(self._data[row])

    def _emit_double_click(self, row: int, col: int) -> None:
        if 0 <= row < len(self._data):
            self.rowDoubleClicked.emit(self._data[row])


def styled_table(parent: QWidget, columns: List[tuple]) -> StyledTableWidget:
    """Factory matching ``StyledTableWidget(parent, columns)``."""
    return StyledTableWidget(parent, columns)
