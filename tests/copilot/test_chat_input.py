# The placeholder is generated by t("copilot.input.placeholder", …)
# which falls back to the default English string when no translation is loaded.
EXPECTED_PLACEHOLDER = "Ask me anything about your fleet..."


def _find_child(widget: QWidget, klass: type, object_name: str | None = None) -> QWidget:
    """Find a single child widget of a given class, optionally matching objectName."""
    children = widget.findChildren(klass)
    if object_name:
        candidates = [c for c in children if c.objectName() == object_name]
        if candidates:
            return candidates[0]
    return children[0] if children else None


