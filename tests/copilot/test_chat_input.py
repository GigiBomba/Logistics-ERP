class TestProcessingState:
    """Input disabled while processing."""

    def test_set_processing_disables_input(self, qt_widget):
        """set_processing(True) disables input and send button."""
        from ui.copilot.widgets.chat_input import ChatInputWidget
        w = ChatInputWidget(qt_widget)
        w.set_processing(True)
        assert w._input.isEnabled() is False
        assert w._send_btn.isEnabled() is False

    def test_set_processing_reenables_input(self, qt_widget):
        """set_processing(False) re-enables input and send button."""
        from ui.copilot.widgets.chat_input import ChatInputWidget
        w = ChatInputWidget(qt_widget)
        w.set_processing(True)
        w.set_processing(False)
        assert w._input.isEnabled() is True
        assert w._send_btn.isEnabled() is True

    def test_processing_does_not_disable_mic(self, qt_widget):
        """Mic button is NOT disabled during processing (voice can interrupt)."""
        from ui.copilot.widgets.chat_input import ChatInputWidget
        w = ChatInputWidget(qt_widget)
        assert w._mic_btn.isEnabled() is True
        w.set_processing(True)
        # Mic should remain enabled
        assert w._mic_btn.isEnabled() is True

    def test_send_does_not_fire_when_disabled(self, qt_widget, qtbot):
        """When processing is True, the input field is disabled and the user
        cannot type or press Enter to send."""
        from ui.copilot.widgets.chat_input import ChatInputWidget
        w = ChatInputWidget(qt_widget)
        qtbot.addWidget(w)

        w.set_processing(True)
        assert w._input.isEnabled() is False
        assert w._send_btn.isEnabled() is False

        # Direct _on_send signal is still callable internally (it reads input),
        # but the real guard is that the input is disabled so the user
        # cannot press Enter. Verify input is effectively blocked.
        w._input.setText("should not send")
        # Simulate what happens when Enter is pressed on a disabled field:
        # returnPressed is NOT emitted by Qt when the widget is disabled.
        # We verify the disabled state is correct.
        assert w._input.isEnabled() is False


